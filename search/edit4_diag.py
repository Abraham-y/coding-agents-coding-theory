"""Classification of alphabet-symmetric quaternary single-edit codes at n = 6.

WHY. The natural symmetry group of the confusability graph is S_4 x C_2 (symbol
permutations, order 24, times word reversal), of order 48. `search/edit4.py`
parameterises invariance cells as "H <= S_4, optionally with reversal", which
reaches only the 22 product-form classes of the 33 in S_4 x C_2. The other
11 are DIAGONAL: generated by elements such as ((1,0,3,2), reverse) -- "swap
0<->1 and 2<->3, then reverse the word" -- where neither the permutation nor the
reversal lies in the group on its own. Those cells were never parameterised, so
nothing is known about them. This file closes that gap and sweeps all 33.

GROUP ACTION. For g = (p, r) in S_4 x C_2 the word map is
    T_g(w) = R^r(P_p(w)),     P_p(w)_i = p(w_i),   R = reversal.
P and R commute, so T_{g}T_{h} = T_{gh} with (p,r)(q,s) = (p o q, r xor s):
this is a genuine action, and it is what makes `apply_t` reusable verbatim.

By the orbit reduction lemma (lean/OrbitReduction, part_c, sorry-free) the
maximum H-invariant code equals the maximum weight of a family of pairwise
compatible internally-independent orbits, i.e. an MWIS on the orbit graph.

ARITHMETIC FILTER. Independently of any search, a size is attainable in a cell
only if it is a subset sum of the usable orbit sizes. This is what rules out
113 in several classes outright (e.g. under a fixed-point-free involution every
orbit has size 2, so invariant codes have even size and 113 is impossible --
the next attainable value above 112 is 114, the literature record).

Run:
    python search/edit4_diag.py --n 6 --classes        # census + arithmetic only (fast)
    python search/edit4_diag.py --n 6 --sweep --seeds 4 --workers 4
"""

from __future__ import annotations

import argparse
import itertools
import json
import os
import sys
import time
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from search.edit4 import (  # noqa: E402
    ALPHABET, PUBLISHED, Edit4Graph, orbits_of, orbit_problem, verify_edit4,
)
from search.edit4_orbit_ls import ils, independent_check  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# RESULTS_DIR is overridable so verification runs (reproduce.sh) do not write
# into results/, which would make any count of that directory drift.
RESULTS_DIR = os.environ.get("FUNMATH_RESULTS_DIR", os.path.join(ROOT, "results"))
BEST_DIR = os.path.join(ROOT, "best")

IDENT = ((0, 1, 2, 3), 0)


# ---------------------------------------------------------------------------
# the group S_4 x C_2 and its subgroups up to conjugacy
# ---------------------------------------------------------------------------


def gmul(a, b):
    (pa, ra), (pb, rb) = a, b
    return (tuple(pa[pb[i]] for i in range(4)), ra ^ rb)


def ginv(a):
    p, r = a
    q = [0] * 4
    for i, v in enumerate(p):
        q[v] = i
    return (tuple(q), r)


def group_elements():
    return [(p, r) for p in itertools.permutations(range(4)) for r in (0, 1)]


def closure(gens):
    S = {IDENT} | set(gens)
    changed = True
    while changed:
        changed = False
        for a in list(S):
            for b in list(S):
                c = gmul(a, b)
                if c not in S:
                    S.add(c)
                    changed = True
    return frozenset(S)


def all_subgroups():
    """Every subgroup of S_4 x C_2 (98 of them, in 33 conjugacy classes).

    NOTE, and the reason this function is written the slow way: an earlier
    version closed over PAIRS of generators, on the stated assumption that every
    subgroup of S_4 x C_2 is 2-generated. That assumption is FALSE -- the group
    contains elementary abelian C_2^3 subgroups, which need three -- so it found
    91 of 98 subgroups and 30 of 33 classes, silently missing three product-form
    classes (C_2^3 twice, and D_4 x C_2). The arithmetic check that exposes it:
    S_4 has 11 conjugacy classes of subgroups, so the product-form classes "H"
    and "H x C_2" already number 11 + 11 = 22, and 22 + 11 diagonal = 33.
    """
    G = group_elements()
    subs = set()
    for a in G:
        for b in G:
            subs.add(closure([a, b]))
    for H in list(subs):                      # third generator closes the gap
        for g in G:
            subs.add(closure(list(H) + [g]))
    assert len(subs) == 98, f"expected 98 subgroups, got {len(subs)}"
    return subs


def conjugacy_classes():
    """One representative per conjugacy class, with class size and a name."""
    G = group_elements()
    subs = all_subgroups()
    seen, out = set(), []
    for H in sorted(subs, key=lambda S: (len(S), sorted(S))):
        if H in seen:
            continue
        cls = {frozenset(gmul(gmul(g, h), ginv(g)) for h in H) for g in G}
        seen |= cls
        out.append({"H": H, "order": len(H), "class_size": len(cls),
                    "diagonal": not is_product_form(H), "name": name_of(H)})
    return out


def is_product_form(H):
    """H = K or K x C_2 for some K <= S_4 (i.e. reachable by the old sweep)."""
    return all((p, 0) in H for p, _ in H)


def name_of(H):
    perms = {p for p, _ in H}
    has_pure_rev = (IDENT[0], 1) in H
    kind = "product" if is_product_form(H) else "DIAGONAL"
    gens = sorted(h for h in H if h != IDENT)
    lead = gens[0] if gens else IDENT
    return (f"|H|={len(H)} {kind} "
            f"[proj|S4|={len(perms)}{', rev' if has_pure_rev else ''}] "
            f"gen~{lead[0]}{'+rev' if lead[1] else ''}")


def transforms_of(H):
    """Word maps for H, in the ('f'/'r', perm, table) form `apply_t` expects."""
    out = []
    for p, r in sorted(H):
        table = {ALPHABET[i]: ALPHABET[p[i]] for i in range(4)}
        out.append(("r" if r else "f", p, table))
    return out


# ---------------------------------------------------------------------------
# arithmetic feasibility: which sizes can a cell possibly attain?
# ---------------------------------------------------------------------------


def attainable_sizes(size_counts, upper):
    """Bitset of subset sums of the usable orbit-size multiset, capped at `upper`."""
    reach = 1  # bit i set <=> sum i attainable
    mask = (1 << (upper + 1)) - 1
    for sz, cnt in size_counts.items():
        # binary splitting keeps this linear-ish in log(cnt)
        k = 1
        while cnt > 0:
            take = min(k, cnt)
            reach |= (reach << (sz * take)) & mask
            cnt -= take
            k *= 2
    return reach


# ---------------------------------------------------------------------------
# per-cell work
# ---------------------------------------------------------------------------


def cell_instance(g, H):
    orbits = orbits_of(g, transforms_of(H))
    usable, edges = orbit_problem(g, orbits)
    k = len(usable)
    adj = [[] for _ in range(k)]
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)
    return usable, adj, [len(o) for o in usable], orbits


def _diag_work(job):
    """Module-level worker (macOS spawn must import it)."""
    n, gens, seed, seconds = job
    g = Edit4Graph(n)
    H = closure([(tuple(p), r) for p, r in gens])
    usable, adj, weights, orbits = cell_instance(g, H)
    sel, wt, iters = ils(weights, adj, seed=seed, time_limit=seconds)
    words = sorted(g.words[v] for i in sel for v in usable[i])
    return {"seed": seed, "weight": wt, "iters": iters, "words": words}


def analyse(g, H, targets=(113, 114)):
    usable, adj, weights, orbits = cell_instance(g, H)
    all_sizes = Counter(len(o) for o in orbits)
    usable_sizes = Counter(weights)
    reach = attainable_sizes(usable_sizes, max(targets) + 2)
    return {
        "orbits_total": len(orbits),
        "orbits_usable": len(usable),
        "orbit_edges": sum(len(a) for a in adj) // 2,
        "orbit_sizes_all": dict(all_sizes),
        "orbit_sizes_usable": dict(usable_sizes),
        "attainable": {str(t): bool((reach >> t) & 1) for t in targets},
        "ub_sum_usable": sum(weights),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=6)
    ap.add_argument("--classes", action="store_true",
                    help="census + arithmetic feasibility only, no search")
    ap.add_argument("--sweep", action="store_true")
    ap.add_argument("--seeds", type=int, default=4)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--max-seconds", type=float, default=300.0)
    args = ap.parse_args()

    t0 = time.time()
    g = Edit4Graph(args.n)
    classes = conjugacy_classes()
    prod = [c for c in classes if not c["diagonal"]]
    diag = [c for c in classes if c["diagonal"]]
    print(f"Edit4 G({args.n}): {g.num_vertices} vertices, {len(g.cliques)} cliques")
    print(f"S_4 x C_2 (order 48): {len(classes)} conjugacy classes of subgroups "
          f"-- {len(prod)} product-form, {len(diag)} DIAGONAL (never swept before)\n")

    rows = []
    for c in sorted(classes, key=lambda c: (-c["order"], c["diagonal"])):
        a = analyse(g, c["H"])
        rows.append({**{k: v for k, v in c.items() if k != "H"}, **a,
                     "gens": sorted([list(p), r] for p, r in c["H"])})
        flag = "DIAG" if c["diagonal"] else "    "
        n113 = "yes" if a["attainable"]["113"] else "NO "
        n114 = "yes" if a["attainable"]["114"] else "NO "
        print(f"  {flag} |H|={c['order']:>2}  orbits {a['orbits_total']:>5} "
              f"({a['orbits_usable']:>4} usable)  sizes {a['orbit_sizes_usable']}"
              f"   113 attainable? {n113}  114? {n114}")

    os.makedirs(RESULTS_DIR, exist_ok=True)
    stamp = time.strftime("%Y%m%dT%H%M%S")
    if args.classes:
        path = os.path.join(RESULTS_DIR, f"edit4_classes_n{args.n}_{stamp}.json")
        with open(path, "w") as fh:
            json.dump({"n": args.n, "group": "S_4 x C_2", "classes": rows,
                       "elapsed_seconds": round(time.time() - t0, 1)}, fh, indent=2)
        print(f"\nlog: {path}")
        no113 = [r for r in rows if not r["attainable"]["113"]]
        print(f"\nclasses where 113 is arithmetically IMPOSSIBLE: {len(no113)}/{len(rows)}")
        print(f"classes where 114 is attainable in principle   : "
              f"{sum(1 for r in rows if r['attainable']['114'])}/{len(rows)}")
        return 0

    if args.sweep:
        from multiprocessing import Pool
        results = []
        for r in sorted(rows, key=lambda r: r["orbits_usable"]):
            # budget scales with instance size; tiny cells need almost nothing
            secs = max(20.0, min(args.max_seconds, r["orbits_usable"] / 8.0))
            gens = [(tuple(p), rr) for p, rr in r["gens"]]
            jobs = [(args.n, gens, s, secs) for s in range(1, args.seeds + 1)]
            with Pool(min(args.workers, len(jobs))) as pool:
                out = pool.map(_diag_work, jobs)
            out.sort(key=lambda x: -x["weight"])
            best = out[0]
            words = sorted(best["words"])
            ok, size, reason = verify_edit4(words, args.n)
            rec = {**r, "search_best": best["weight"], "verified": ok,
                   "by_seed": [x["weight"] for x in out], "seconds_per_seed": secs}
            results.append(rec)
            tag = "DIAG" if r["diagonal"] else "    "
            print(f"  {tag} |H|={r['order']:>2} ({r['orbits_usable']:>4} usable, "
                  f"{secs:>5.0f}s x{args.seeds})  best {best['weight']:>4}  "
                  f"verified={ok} {reason}", flush=True)
            if ok and best["weight"] >= 113:
                bad = independent_check(words)
                print(f"       >= 113 -- independent Levenshtein: {bad} bad pairs",
                      flush=True)
                if bad == 0:
                    os.makedirs(BEST_DIR, exist_ok=True)
                    p = os.path.join(BEST_DIR,
                                     f"edit4_n{args.n}_diag_size{size}.txt")
                    with open(p, "w") as fh:
                        fh.write(f"# quaternary single-edit code, n = {args.n}\n")
                        fh.write(f"# size = {size}, invariant under {r['name']}\n")
                        for w in words:
                            fh.write(w + "\n")
                    print(f"       saved {p} -- rule 6: bug until re-verified fresh",
                          flush=True)
        path = os.path.join(RESULTS_DIR, f"edit4_diag_sweep_n{args.n}_{stamp}.json")
        with open(path, "w") as fh:
            json.dump({"n": args.n, "group": "S_4 x C_2", "seeds": args.seeds,
                       "cells": results,
                       "published_best": PUBLISHED.get(args.n, {}).get("best"),
                       "literature_best": 114,
                       "elapsed_seconds": round(time.time() - t0, 1)}, fh, indent=2)
        print(f"\nlog: {path}")
        best = max(results, key=lambda r: r["search_best"])
        print(f"best over all 33 classes: {best['search_best']}  ({best['name']})")
        return 0

    ap.error("pass --classes or --sweep")


if __name__ == "__main__":
    raise SystemExit(main())

"""Prescribed-symmetry search for binary s-deletion-correcting codes.

The confusability graph for A_s(n) is invariant under complement (0<->1) and
reversal, a group of order 4. Every subgroup of it gives an invariance class, and
an invariant code is a union of orbits, so the search collapses from 2^n words to
the orbit count. This is the same reduction that produced E_4(6,3) >= 120 in the
quaternary family; it had not been applied here with a real seed budget.

Run:  python search/binary_orbit.py --n 12 --s 2 --target 37
"""
from __future__ import annotations
import argparse, hashlib, itertools, json, os, sys, time
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from multiprocessing import Pool
import search.edit4_orbit_ls as L
from verify import verify as verify_binary, deletion_ball

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_W = _A = None

def _init(w, a):
    global _W, _A
    _W, _A = w, a

def _run(job):
    seed, secs = job
    sel, wt, _ = L.ils(_W, _A, seed=seed, time_limit=secs)
    return {"seed": seed, "weight": wt, "sel": sel}

def build_graph(n, s):
    words = ["".join(w) for w in itertools.product("01", repeat=n)]
    idx = {w: i for i, w in enumerate(words)}
    buckets = {}
    for i, w in enumerate(words):
        for t in deletion_ball(w, s):
            buckets.setdefault(t, []).append(i)
    adj = [set() for _ in words]
    for members in buckets.values():
        if len(members) < 2:
            continue
        for a in range(len(members)):
            for b in range(a + 1, len(members)):
                adj[members[a]].add(members[b]); adj[members[b]].add(members[a])
    return words, idx, adj

def transforms(n, comp, rev):
    """The four maps generated by complement and reversal, restricted to a subgroup."""
    fns = [lambda w: w]
    if comp: fns.append(lambda w: "".join("1" if c == "0" else "0" for c in w))
    if rev:  fns.append(lambda w: w[::-1])
    if comp and rev:
        fns.append(lambda w: "".join("1" if c == "0" else "0" for c in w)[::-1])
    return fns

def orbit_instance(words, idx, adj, fns):
    seen, orbits = set(), []
    for i, w in enumerate(words):
        if i in seen: continue
        orb = sorted({idx[f(w)] for f in fns})
        seen.update(orb); orbits.append(orb)
    usable = [o for o in orbits
              if not any(o[b] in adj[o[a]] for a in range(len(o)) for b in range(a + 1, len(o)))]
    nbr = [set().union(*(adj[v] for v in o)) for o in usable]
    pos = {v: k for k, o in enumerate(usable) for v in o}
    oadj = [[] for _ in usable]
    for k, o in enumerate(usable):
        hit = {pos[v] for v in nbr[k] if v in pos and pos[v] != k}
        oadj[k] = sorted(hit)
    return usable, oadj, [len(o) for o in usable]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, required=True)
    ap.add_argument("--s", type=int, required=True)
    ap.add_argument("--target", type=int, required=True)
    ap.add_argument("--seeds", type=int, default=8)
    ap.add_argument("--seconds", type=float, default=600.0)
    ap.add_argument("--workers", type=int, default=4)
    a = ap.parse_args()

    t0 = time.time()
    words, idx, adj = build_graph(a.n, a.s)
    print(f"A_{a.s}({a.n}): {len(words)} vertices, "
          f"{sum(len(x) for x in adj)//2} edges; target {a.target}", flush=True)
    out, best = [], 0
    for comp, rev in [(True, True), (True, False), (False, True)]:
        fns = transforms(a.n, comp, rev)
        usable, oadj, w = orbit_instance(words, idx, adj, fns)
        name = f"comp={comp} rev={rev} (|G|={len(fns)})"
        if not usable:
            print(f"  {name}: no usable orbits", flush=True); continue
        with Pool(a.workers, initializer=_init, initargs=(w, oadj)) as pool:
            res = pool.map(_run, [(sd, a.seconds) for sd in range(1, a.seeds + 1)])
        res.sort(key=lambda r: -r["weight"]); top = res[0]
        code = sorted(words[v] for i in top["sel"] for v in usable[i])
        ok, size, why = verify_binary(code, a.n, a.s)
        print(f"  {name}: {len(usable)} usable orbits  best {top['weight']:>4}  "
              f"seeds {[r['weight'] for r in res]}  verified={ok} {why}", flush=True)
        out.append({"group": name, "usable": len(usable), "best": top["weight"],
                    "by_seed": [r["weight"] for r in res], "verified": ok})
        if ok: best = max(best, size)
        if ok and size > a.target:
            body = "".join(x + "\n" for x in code)
            d = hashlib.sha256(body.encode()).hexdigest()
            p = os.path.join(ROOT, "best", f"n{a.n}_s{a.s}_size{size}_orbit.txt")
            with open(p, "w") as fh:
                fh.write(f"# n = {a.n}\n# s = {a.s}\n# size = {size}\n"
                         f"# invariant under {name}\n# sha256(codewords) = {d}\n{body}")
            print(f"     *** {size} BEATS {a.target}; saved {p} ***", flush=True)
        json.dump({"n": a.n, "s": a.s, "target": a.target, "cells": out, "best": best,
                   "seeds": a.seeds, "seconds": a.seconds,
                   "elapsed_seconds": round(time.time() - t0, 1)},
                  open(os.path.join(ROOT, "results", f"binary_orbit_n{a.n}_s{a.s}.json"), "w"), indent=2)
    print(f"\nbest {best}  target {a.target}", flush=True)

if __name__ == "__main__":
    main()
